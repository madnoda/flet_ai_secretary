from __future__ import annotations

from pathlib import Path
import tomllib

ROOT = Path(__file__).resolve().parent
CONFIG = ROOT / "config.toml"
OUTPUT = ROOT / "src" / "client_config.py"


def main() -> int:
    if not CONFIG.exists():
        raise SystemExit(f"config.toml not found: {CONFIG}")
    with CONFIG.open("rb") as f:
        cfg = tomllib.load(f)
    client = cfg.get("client", {})
    host = str(client.get("server_host", "127.0.0.1"))
    voice_port = int(client.get("voice_port", 50000))
    schedule_port = int(client.get("schedule_port", 8766))
    character = cfg.get("character", {})
    normal_image = str(character.get("normal_image", "secretary_normal.png"))
    talking_image = str(character.get("talking_image", "secretary_mouth_open.png"))
    happy_image = str(character.get("happy_image", "secretary_happy.png"))
    warning_image = str(character.get("warning_image", "secretary_warning.png"))
    text = f'''# Auto-generated by generate_client_config.py.\n# Do not edit this file directly.\nAI_HOST = {host!r}\nVOICE_PORT = {voice_port}\nSCHEDULE_PORT = {schedule_port}\nCHARACTER_NORMAL = {normal_image!r}\nCHARACTER_TALKING = {talking_image!r}\nCHARACTER_HAPPY = {happy_image!r}\nCHARACTER_WARNING = {warning_image!r}\n'''
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"written: {OUTPUT}")
    print(f"AI_HOST={host} VOICE_PORT={voice_port} SCHEDULE_PORT={schedule_port}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
